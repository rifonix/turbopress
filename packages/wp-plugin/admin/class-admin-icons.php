	/**
	 * Render an inline SVG icon. Decorative (aria-hidden); put accessible
	 * text next to it.
	 */
	public static function render(string $name, int $size = 18): string {
		$body = self::ICONS[$name] ?? '<circle cx="12" cy="12" r="9"/>';
		$size = max(10, min(64, $size));
		return sprintf(
			'<svg class="wpins-icon" width="%1$d" height="%1$d" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">%2$s</svg>',
			$size,
			$body
		);
	}

	/**
	 * Brand-accent bolt as an admin-menu data URI (WordPress cannot recolor
	 * SVG menu icons, so the accent color is baked in).
	 */
	public static function menu_icon_uri(): string {
		$svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#f03e2f" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M13 2 3 14h7l-1 8 10-12h-7l1-8z"/></svg>';
		return 'data:image/svg+xml;base64,' . base64_encode($svg);
	}
